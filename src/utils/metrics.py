import torch
import nltk
from nltk.tokenize import word_tokenize

from torchmetrics.text import BLEUScore, ROUGEScore
from torchmetrics import MetricCollection
from nltk.translate import meteor_score
from pycocoevalcap.cider.cider import Cider

# Required NLTK downloads (executed only once)
nltk.download('wordnet', quiet=True)
nltk.download('punkt', quiet=True) # Required for word_tokenize

class Metrics:
    def __init__(self, device):
        """
        Initializes a collection of standard metrics.
        """
        self.device = device
        
        # Initialize metrics via torchmetrics (BLEU & ROUGE)
        self.caption_metrics = MetricCollection({
            "bleu4": BLEUScore(n_gram=4),
            "rouge": ROUGEScore(),
        }).to(device)
        
        # Initialize CIDEr
        self.cider_scorer = Cider()

    def compute_caption_quality(self, predictions, targets):
        """
        Args:
            predictions (list of str): The captions generated by your model.
            targets (list of str or list of list of str): The ground truth captions.
        Returns:
            dict: Dictionary containing all calculated scores.
        """
        # Format targets to ensure they are always a list of lists
        if isinstance(targets[0], list):
            formatted_targets = targets
        else:
            formatted_targets = [[t] for t in targets]
        
        # 1. Calculate BLEU and ROUGE (Torchmetrics)
        results = self.caption_metrics(predictions, formatted_targets)
        
        # Clean up the output dictionary
        output = {}
        for k, v in results.items():
            if isinstance(v, dict):
                for sub_k, sub_v in v.items():
                    output[f"{k}_{sub_k}"] = sub_v.item()
            else:
                output[k] = v.item()

        # 2. Calculate METEOR (NLTK)
        meteor_scores = []
        for pred, refs in zip(predictions, formatted_targets):
            pred_tokens = word_tokenize(pred)
            ref_tokens_list = [word_tokenize(ref) for ref in refs]
            
            score = meteor_score.meteor_score(ref_tokens_list, pred_tokens)
            meteor_scores.append(score)
        
        # Average METEOR score for the batch
        output['meteor'] = sum(meteor_scores) / len(meteor_scores) if meteor_scores else 0.0

        # 3. Calculate CIDEr
        cider_preds = {}
        cider_refs = {}
        
        for i, (pred, refs) in enumerate(zip(predictions, formatted_targets)):
            img_id = str(i)
            
            cider_preds[img_id] = [pred.lower()]
            cider_refs[img_id] = [ref.lower() for ref in refs]
            
        cider_score, _ = self.cider_scorer.compute_score(cider_refs, cider_preds)
        output['cider'] = cider_score
        
        return output

    def reset(self):
        """Clear the metric states for the next epoch."""
        self.caption_metrics.reset()