import torch
import nltk
from torchmetrics.text import BLEUScore, ROUGEScore
from torchmetrics import MetricCollection

class Metrics:
    def __init__(self, device):
        """
        Initializes a collection of standard metrics.
        """
        self.device = device
        
        self.caption_metrics = MetricCollection({
            "bleu4": BLEUScore(n_gram=4),
            "rouge": ROUGEScore(),
        }).to(device)

    def compute_caption_quality(self, predictions, targets):
        """
        Args:
            predictions (list of str): The captions generated by your model.
            targets (list of str): The ground truth captions.
        Returns:
            dict: Dictionary containing the calculated scores.
        """
        # If targets is already a list of lists, don't wrap it again
        if isinstance(targets[0], list):
            formatted_targets = targets
        else:
            formatted_targets = [[t] for t in targets]
        
        # Calculate all metrics in the collection
        results = self.caption_metrics(predictions, formatted_targets)
        
        # Clean up the output to be a simple dict of floats
        output = {}
        for k, v in results.items():
            if isinstance(v, dict):
                # ROUGE returns a dict of sub-metrics (rougeL, rouge1, etc.)
                for sub_k, sub_v in v.items():
                    output[f"{k}_{sub_k}"] = sub_v.item()
            else:
                output[k] = v.item()
        
        return output

    def reset(self):
        """Clear the metric states for the next epoch."""
        self.caption_metrics.reset()